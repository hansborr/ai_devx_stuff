import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { runDocGenerator } from "../lib/doc-generator.js";
import { lintRatchets } from "../lint-ratchet/lint-ratchet-config.js";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const outputPath = join(repoRoot, "eslint-config/ratchet-restricted-disable-rules.generated.js");

function renderRestrictedDisableRules(): string {
  const ruleIds = [...new Set(lintRatchets.map((ratchet) => ratchet.ruleId))].sort((left, right) =>
    left.localeCompare(right),
  );
  return [
    "// @ts-check",
    "// Generated by scripts/harness/generate-restricted-disable-rules.ts. Do not edit by hand.",
    "",
    "export const ratchetRestrictedDisableRuleIds = Object.freeze([",
    ...ruleIds.map((ruleId) => `  ${JSON.stringify(ruleId)},`),
    "]);",
    "",
  ].join("\n");
}

function main(): void {
  runDocGenerator({
    outputPath,
    refreshCommand: "lint:restricted-disable-rules",
    render: () => ({
      rendered: renderRestrictedDisableRules(),
      wroteSuffix: ` (${String(lintRatchets.length)} ratchet rule source(s))`,
    }),
  });
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
