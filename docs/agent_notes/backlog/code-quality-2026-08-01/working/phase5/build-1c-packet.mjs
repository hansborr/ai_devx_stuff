#!/usr/bin/env node
/**
 * Phase 5 step 1c packet builder (dependency-free ESM; run with `bun <path>` or `node <path>`).
 *
 * Pools a round's step-1b reject-audit files into one candidate set and emits a
 * compact index of every authored pack file, so the single pooled-adjudication
 * consult sees the whole promotion pool and every existing leaf title at once.
 *
 * usage: node build-1c-packet.mjs [--round N]   (default 1)
 *
 * Round 1 pools `reject-audit-{b,c,d-01..d-09}.json` into `working/phase5/1c/`;
 * every later round N pools `reject-audit-r<N>-*.json` into `working/phase5/1c-rN/`
 * and indexes the pack as it stands *after* the previous round's authoring, so a
 * round's dedup always rules against its predecessor's leaves too.
 *
 * Outputs (relative to the pack root):
 *   working/phase5/1c[-rN]/pooled-candidates.json
 *   working/phase5/1c[-rN]/leaf-index.md
 *
 * Each round's outputs are a historical record of what that consult actually saw
 * (round 1: a 206-file pack; round 2: 232). Re-running an earlier `--round`
 * overwrites its index with the pack as it stands today and falsifies the
 * record; restore from git if you do.
 */
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const packRoot = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const phase5 = join(packRoot, 'working', 'phase5');
const roundArg = process.argv.indexOf('--round');
const round = roundArg === -1 ? 1 : Number(process.argv[roundArg + 1]);
if (!Number.isSafeInteger(round) || round < 1) throw new Error(`--round must be an integer >= 1, got ${round}`);

const outDir = join(phase5, round === 1 ? '1c' : `1c-r${round}`);
mkdirSync(outDir, { recursive: true });

// Round 1's files carry no round tag; later rounds are `reject-audit-r<N>-*.json`.
const roundOf = (f) => Number(/^reject-audit-r(\d+)-/.exec(f)?.[1] ?? 1);
const auditFiles = readdirSync(phase5)
  .filter((f) => /^reject-audit-.*\.json$/.test(f) && roundOf(f) === round)
  .sort();

const candidates = [];
const perConsult = [];
for (const file of auditFiles) {
  const json = JSON.parse(readFileSync(join(phase5, file), 'utf8'));
  const list = json.promotionCandidates ?? [];
  perConsult.push({ consult: json.consult ?? file, file, count: list.length });
  for (const c of list) candidates.push({ ...c, sourceFile: `working/phase5/${file}` });
}

const ids = candidates.map((c) => c.promotionId);
const dupes = ids.filter((id, i) => ids.indexOf(id) !== i);
if (dupes.length) throw new Error(`duplicate promotionIds: ${dupes.join(', ')}`);

writeFileSync(
  join(outDir, 'pooled-candidates.json'),
  `${JSON.stringify(
    {
      step: '1c-input',
      builtFrom: perConsult,
      candidateCount: candidates.length,
      candidates,
    },
    null,
    2,
  )}\n`,
);

// --- leaf index -------------------------------------------------------------
const packFiles = readdirSync(packRoot)
  .filter((f) => /^\d{3}[-.].*\.md$/.test(f))
  .sort();

const rows = [];
for (const file of packFiles) {
  const text = readFileSync(join(packRoot, file), 'utf8');
  const lines = text.split('\n');
  const title = (lines.find((l) => l.startsWith('# ')) ?? '# ?').replace(/^#\s*/, '').trim();
  const header =
    lines.find((l) => l.startsWith('Theme:')) ??
    lines.find((l) => l.startsWith('Date:')) ??
    '';
  rows.push(`- \`${file}\` — ${title}\n  - ${header.trim()}`);
}

writeFileSync(
  join(outDir, 'leaf-index.md'),
  [
    `# Authored pack files (Phase-5 step 1c reference${round === 1 ? '' : `, round ${round}`})`,
    '',
    round === 1
      ? `${rows.length} files: 203 leaves plus 107/108/109-PLAN.md companions.`
      : `${rows.length} files: ${rows.length - 3} leaves — including every leaf authored by an earlier reject-audit round — plus the 107/108/109-PLAN.md companions.`,
    'Generated by `working/phase5/build-1c-packet.mjs`. Titles and header fields only —',
    'open the file itself before ruling that a candidate duplicates it.',
    '',
    ...rows,
    '',
  ].join('\n'),
);

console.log(`round ${round}: pooled ${candidates.length} candidates from ${auditFiles.length} files`);
console.log(`indexed ${rows.length} pack files`);
